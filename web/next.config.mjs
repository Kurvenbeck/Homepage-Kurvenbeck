// Content-Security-Policy. 'unsafe-inline' bei Scripts ist für Next.js' Inline-
// Hydration (ohne Nonce-Middleware) nötig; Styles nutzen Inline-Attribute.
// Verbindungen: eigene Origin + Supabase (Auth/DB aus Browser-Client).
// Nur im Dev-Server (`npm run dev`): Next.js braucht dort eval() (React Refresh) und
// einen WebSocket für Hot Reload — sonst hydriert keine Seite. Production bleibt streng.
const dev = process.env.NODE_ENV === "development";

const csp = [
  "default-src 'self'",
  `script-src 'self' 'unsafe-inline'${dev ? " 'unsafe-eval'" : ""}`,
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:",
  "font-src 'self' data:",
  `connect-src 'self' https://*.supabase.co${dev ? " ws://localhost:*" : ""}`,
  "frame-ancestors 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "object-src 'none'",
].join("; ");

const securityHeaders = [
  { key: "Content-Security-Policy", value: csp },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  {
    key: "Permissions-Policy",
    value: "camera=(), microphone=(), geolocation=(), payment=()",
  },
];

const nextConfig = {
  reactStrictMode: true,
  async headers() {
    return [{ source: "/:path*", headers: securityHeaders }];
  },
};

export default nextConfig;
